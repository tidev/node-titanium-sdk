import { describe, expect, it } from 'vitest';
import { pngInfo } from '../../src/util/png-info.js';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

describe('pngInfo', () => {
	it('should return the width, height, and alpha channel of a PNG buffer', () => {
		const buf = Buffer.from([
			0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
			0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
			0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
			0x08, 0x02, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
			0x89, 0x00, 0x00, 0x00, 0x01, 0x74, 0x52, 0x4E,
			0x53, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		]);
		expect(pngInfo(buf)).toEqual({
			width: 1,
			height: 1,
			alpha: false,
		});
	});

	it('should return the width, height, and alpha channel of a PNG buffer with an alpha channel', () => {
		const buf = Buffer.from([
			0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
			0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
			0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
			0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
			0x89, 0x00, 0x00, 0x00, 0x01, 0x74, 0x52, 0x4E,
			0x53, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		]);
		expect(pngInfo(buf)).toEqual({
			width: 1,
			height: 1,
			alpha: true,
		});
	});

	it('should return the width, height, and alpha channel of a PNG buffer with a width and height of 0', () => {
		const buf = Buffer.from([
			0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
			0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x08, 0x02, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
			0x89, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		]);
		expect(pngInfo(buf)).toEqual({
			width: 0,
			height: 0,
			alpha: false,
		});
	});

	it('should return the width, height, and alpha channel of a PNG buffer with a width and height of 0 and an alpha channel', () => {
		const buf = Buffer.from([
			0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
			0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
			0x89, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		]);
		expect(pngInfo(buf)).toEqual({
			width: 0,
			height: 0,
			alpha: true,
		});
	});

	it('should return the width, height, and alpha channel of a PNG buffer with a width and height of 0 and an alpha channel', () => {
		const buf = Buffer.from([
			0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
			0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
			0x89, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		]);
		expect(pngInfo(buf)).toEqual({
			width: 0,
			height: 0,
			alpha: true,
		});
	});

	it('should return the width, height, and alpha channel of a PNG file', () => {
		const bytes = readFileSync(join(import.meta.filename, '..', 'assets', 'titanium-logo.png'));
		expect(pngInfo(bytes)).toEqual({
			width: 1024,
			height: 1024,
			alpha: true,
		});
	});
});
